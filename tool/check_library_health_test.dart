    expectV(fx, 'child-type', file: 'controls/probe.dart', scope: 'Probe.run', detail: 'Tile');
  });

  test('identifiers inside doc comment references report nothing', () {
    final fx = Fx.baseline();
    fx.write(
      'controls/probe.dart',
      '/// See [kIsWeb], [TargetPlatform.android], [Platform.isIOS], [Foo.platform], [hitTestInView], [Foo.runtimeType]\n'
      'class Probe {\n'
      '  /// See [kIsWeb], [TargetPlatform.android], [Platform.isIOS], [Foo.platform], [hitTestInView], [Foo.runtimeType]\n'
      '  void run() {}\n'
      '}\n',
    );
    expectClean(fx);
  });

  test('--init on a file with a syntax error exits 2 and writes no list', () {
    final fx = Fx();
    defaults().forEach(fx.write);
    fx.write('controls/bad.dart', 'class Bad {{{ void\n');
    final r = fx.run(['--init']);
    check(r.code == 2, 'expected 2, got ${r.code}\n${r.text}');
    check(!fx.has(allowPath) && !fx.has(apiPath), 'no list may be written');
  });

  test('--prune with a parse error reports parse, exits 1, leaves the lists untouched', () {
    final fx = Fx.baseline({'controls/probe.dart': m(growthCall)});
    // Something prunable, so an unguarded --prune would rewrite the lists.
    fx.write('controls/probe.dart', m('final a = 1;'));
    fx.write('controls/bad.dart', 'class Bad {{{ void\n');
    final allowBefore = fx.f(allowPath).readAsBytesSync();
    final apiBefore = fx.f(apiPath).readAsBytesSync();
    final r = fx.run(['--prune']);
    check(r.code == 1, 'expected 1, got ${r.code}\n${r.text}');
    check(hasLine(r, 'parse ', 'controls/bad.dart'), 'missing parse line\n${r.text}');
    check(_same(fx.f(allowPath).readAsBytesSync(), allowBefore), 'allowlist changed');
    check(_same(fx.f(apiPath).readAsBytesSync(), apiBefore), 'public_api changed');
  });

  test('a private data class is not confused with a same-named widget in another file', () {
    final fx = Fx.baseline();
    fx.write('controls/b.dart', 'class _Item extends StatelessWidget {}\n');
    fx.write('controls/a.dart', 'class _Item {}\n${m('final b = x is _Item;', cls: 'A')}');
    final r = expectClean(fx);
    check(!hasIssue(r, 'child-type', file: 'controls/a.dart'), r.text);
  });

  test('a private widget is still checked in its own file', () {
    final fx = Fx.baseline();
    fx.write('controls/d.dart', 'class _Row {}\n');
    fx.write('controls/c.dart', 'class _Row extends StatelessWidget {}\n${m('final b = x is _Row;', cls: 'C')}');
    expectV(fx, 'child-type', file: 'controls/c.dart', scope: 'C.run', detail: '_Row');
  });

  test('MediaQuery.maybeOf(c)!.size is basis MediaQuery.size', () {
    final fx = Fx.baseline();
    fx.write('controls/probe.dart', m('final s = MediaQuery.maybeOf(context)!.size;'));
    expectV(fx, 'basis', file: 'controls/probe.dart', scope: 'Probe.run', detail: 'MediaQuery.size');
  });

  test('(MediaQuery.of(c)).size is basis MediaQuery.size', () {
    final fx = Fx.baseline();
    fx.write('controls/probe.dart', m('final s = (MediaQuery.of(context)).size;'));
    expectV(fx, 'basis', file: 'controls/probe.dart', scope: 'Probe.run', detail: 'MediaQuery.size');
  });
}

bool _same(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return false;
  }
  return true;
}

