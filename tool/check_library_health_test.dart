void guidance() {
  test('no guidance text mentions allowlist, public_api, 清单 or 豁免', () {
    final issues = collected.where((l) {
      final first = l.split(' ').first;
      return (knownRules.contains(first) || first == 'stale') && l.contains(': ');
    }).toList();
    check(issues.length >= 30, 'only ${issues.length} violation lines collected; scan would be vacuous');
    check(issues.any((l) => l.startsWith('growth ')), 'no growth line collected');
    final banned = RegExp('allowlist|public_api|清单|豁免', caseSensitive: false);
    final bad = <String>[];
    for (final l in issues) {
      final g = l.substring(l.indexOf(': ') + 2);
      if (!l.startsWith('stale ') && g.trim().isEmpty) bad.add('empty guidance: $l');
      if (banned.hasMatch(g)) bad.add(l);
    }
    check(bad.isEmpty, 'forbidden words or empty guidance in:\n${bad.take(10).join('\n')}');
  });
}

