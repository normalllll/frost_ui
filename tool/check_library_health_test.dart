// ----------------------------------------------------------------- prune

void prune() {
  test('--prune removes stale, keeps new violations reported, grows nothing', () {
    final fx = Fx.baseline({'controls/probe.dart': m('FocusManager.instance.addEarlyKeyEventHandler(h);')});
    final allowBefore = lineCount(fx.read(allowPath));
    final apiBefore = lineCount(fx.read(apiPath));
    fx.write('controls/probe.dart', m('final a = 1;'));
    fx.write('controls/basis.dart', m('final p = defaultTargetPlatform;', cls: 'B'));
    fx.edit('controls/button.dart', (s) => '${s}class FrostNew {}\n');
    final r = fx.run(['--prune']);
    check(r.code == 1, 'exit ${r.code}\n${r.text}');
    check(hasIssue(r, 'basis', detail: 'defaultTargetPlatform'), 'new basis violation stays\n${r.text}');
    check(hasLine(r, 'public-api ', 'FrostNew'), 'new api stays\n${r.text}');
    check(!r.lines.any((l) => l.startsWith('stale ')), 'stale gone after prune\n${r.text}');
    final allow = fx.read(allowPath);
    final api = fx.read(apiPath);
    check(!allow.contains('addEarlyKeyEventHandler'), 'stale entry removed');
    check(lineCount(allow) == allowBefore - 1, 'allowlist shrank by one');
    check(!allow.contains('defaultTargetPlatform'), 'allowlist gained nothing');
    check(lineCount(api) <= apiBefore && !api.contains('FrostNew'), 'public_api gained nothing');
    check(fx.run().code == 1, 'violations still fail afterwards');
  });
  test('--prune lowers an allowlist count', () {
    final fx = Fx.baseline({'controls/probe.dart': m('FocusManager.instance.addEarlyKeyEventHandler(h);')});
    fx.edit(allowPath, (s) => s.replaceFirst('addEarlyKeyEventHandler\t1\t', 'addEarlyKeyEventHandler\t3\t'));
    final r = fx.run(['--prune']);
    check(r.code == 0, 'exit ${r.code}\n${r.text}');
    check(fx.read(allowPath).contains('addEarlyKeyEventHandler\t1\t'), fx.read(allowPath));
  });
}

