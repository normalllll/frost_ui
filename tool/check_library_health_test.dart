RegExp issue(String rule, {String? file, String? scope, String? detail, String? like}) {
  final f = file == null ? r'\S+' : RegExp.escape(file);
  final s = scope == null ? r'\S+' : RegExp.escape(scope);
  final d = detail != null
      ? RegExp.escape(detail)
      : like != null
      ? '.*${RegExp.escape(like)}.*?'
      : '.+?';
  return RegExp('^${RegExp.escape(rule)} $f:\\d+ $s $d: ');
}

bool hasIssue(Res r, String rule, {String? file, String? scope, String? detail, String? like}) {
  final re = issue(rule, file: file, scope: scope, detail: detail, like: like);
  return r.lines.any(re.hasMatch);
}

bool hasLine(Res r, String prefix, String contains) =>
    r.lines.any((l) => l.startsWith(prefix) && l.contains(contains));

bool hasStale(Res r, String rule, [String contains = '']) => r.lines.any(
  (l) => l.startsWith('stale $rule ') && l.endsWith(': run --prune') && l.contains(contains),
);

/// Runs the checker, expects exit 1 and the issue line.
Res expectV(Fx fx, String rule, {String? file, String? scope, String? detail, String? like, List<String> args = const []}) {
  final r = fx.run(args);
  check(r.code == 1, 'expected exit 1, got ${r.code}\n${r.text}');
  check(
    hasIssue(r, rule, file: file, scope: scope, detail: detail, like: like),
    'missing $rule line (file=$file scope=$scope detail=${detail ?? like})\n${r.text}',
  );
  return r;
}

Res expectClean(Fx fx, [List<String> args = const []]) {
  final r = fx.run(args);
  check(r.code == 0, 'expected exit 0, got ${r.code}\n${r.text}');
  return r;
}

int lineCount(String s) => s.split('\n').where((l) => l.trim().isNotEmpty).length;

// ---------------------------------------------------------------- CLI

void cli() {
  test('--init writes both lists with the baseline marker', () {
    final fx = Fx();
    defaults().forEach(fx.write);
    fx.write('controls/probe.dart', m('FocusManager.instance.addEarlyKeyEventHandler(h);'));
    final r = fx.run(['--init']);
    check(r.code == 0, '--init exit ${r.code}: ${r.text}');
    check(fx.has(allowPath) && fx.has(apiPath), 'both lists written');
    final allow = fx.read(allowPath);
    final api = fx.read(apiPath);
    check(
      allow.split('\n').contains('framework\tcontrols/probe.dart\tProbe.run\taddEarlyKeyEventHandler\t1\t$marker'),
      'allowlist row missing:\n$allow',
    );
    for (final l in api.split('\n').where((l) => l.trim().isNotEmpty && !l.startsWith('#'))) {
      check(l.endsWith('\t$marker'), 'public_api row without marker: $l');
    }
    check(api.contains(marker), 'public_api has marker');
  });

  test('--init public_api rows: class and ctor with sorted params', () {
    final fx = Fx();
    defaults().forEach(fx.write);
    fx.run(['--init']);
    final lines = fx.read(apiPath).split('\n');
    check(lines.contains('class\tFrostButton\tcontrols/button.dart\t-\t$marker'), 'class row:\n${lines.join('\n')}');
    check(
      lines.contains('ctor\tFrostButton.new\tcontrols/button.dart\tlabel,onTap\t$marker'),
      'ctor row:\n${lines.join('\n')}',
    );
  });

  for (final which in ['allowlist', 'public_api', 'both']) {
    test('--init refuses (exit 2, writes nothing) when $which exists', () {
      final fx = Fx();
      defaults().forEach(fx.write);
      if (which != 'public_api') fx.write(allowPath, '# mine\n');
      if (which != 'allowlist') fx.write(apiPath, '# mine\n');
      final r = fx.run(['--init']);
      check(r.code == 2, 'expected 2, got ${r.code}\n${r.text}');
      if (which != 'public_api') check(fx.read(allowPath) == '# mine\n', 'allowlist changed');
      if (which != 'allowlist') check(fx.read(apiPath) == '# mine\n', 'public_api changed');
      if (which == 'allowlist') check(!fx.has(apiPath), 'public_api must not be created');
      if (which == 'public_api') check(!fx.has(allowPath), 'allowlist must not be created');
    });
  }

  test('unknown flag exits 2', () {
    final fx = Fx.baseline();
    check(fx.run(['--bogus']).code == 2, 'exit 2');
  });

  test('clean repo exits 0 with summary line', () {
    final fx = Fx.baseline();
    final r = fx.run();
    check(r.code == 0, 'exit ${r.code}');
    check(r.last == 'library health: 0 violations, 0 stale, 0 growth', 'last line: ${r.last}');
  });

  test('summary counts violations and stale', () {
    final fx = Fx.baseline();
    fx.write('controls/probe.dart', m('final p = defaultTargetPlatform;'));
    final r = fx.run();
    check(r.code == 1, 'exit ${r.code}');
    check(r.last == 'library health: 1 violations, 0 stale, 0 growth', 'last line: ${r.last}');
  });
}

