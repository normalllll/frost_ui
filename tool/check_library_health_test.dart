void publicApi() {
  final newSymbols = {
    'class': 'class FrostNew {}\n',
    'enum': 'enum FrostMode { a, b }\n',
    'top-level function': 'void frostHelper() {}\n',
  };
  newSymbols.forEach((kind, code) {
    test('new $kind fails', () {
      final fx = Fx.baseline();
      fx.edit('controls/button.dart', (s) => s + code);
      final r = fx.run();
      check(r.code == 1, 'exit ${r.code}\n${r.text}');
      final name = RegExp(r'(?:class|enum|void) (\w+)').firstMatch(code)!.group(1)!;
      check(hasLine(r, 'public-api ', name), 'no public-api line for $name\n${r.text}');
    });
  });

  test('new extension method fails', () {
    final fx = Fx.baseline({'controls/ext.dart': 'extension FrostStringX on String {\n  void shout() {}\n}\n', 'frost_ui.dart': "export 'src/foundation/base.dart';\nexport 'src/controls/button.dart';\nexport 'src/controls/ext.dart';\n"});
    fx.edit('controls/ext.dart', (s) => s.replaceFirst('void shout() {}', 'void shout() {}\n  void whisper() {}'));
    final r = fx.run();
    check(r.code == 1, 'exit ${r.code}\n${r.text}');
    check(hasLine(r, 'public-api ', 'FrostStringX.whisper'), r.text);
  });

  test('new constructor parameter fails', () {
    final fx = Fx.baseline();
    fx.write('controls/button.dart', buttonSource.replaceFirst('this.onTap}', 'this.onTap, this.extra}'));
    final r = fx.run();
    check(r.code == 1, 'exit ${r.code}\n${r.text}');
    check(hasLine(r, 'public-api ', 'FrostButton.new'), r.text);
  });

  test('renamed parameter fails', () {
    final fx = Fx.baseline();
    fx.write('controls/button.dart', buttonSource.replaceAll('onTap', 'onPressed'));
    final r = fx.run();
    check(r.code == 1, 'exit ${r.code}\n${r.text}');
    check(hasLine(r, 'public-api ', 'FrostButton.new'), r.text);
  });

  test('symbols in a part file are found', () {
    final fx = Fx.baseline({
      'controls/button.dart': "part 'button_part.dart';\n$buttonSource",
      'controls/button_part.dart': "part of 'button.dart';\nclass FrostPartA {}\n",
    });
    check(fx.read(apiPath).contains('class\tFrostPartA\t'), 'part symbol listed:\n${fx.read(apiPath)}');
    fx.edit('controls/button_part.dart', (s) => '${s}class FrostPartB {}\n');
    final r = fx.run();
    check(r.code == 1 && hasLine(r, 'public-api ', 'FrostPartB'), r.text);
  });

  test('symbols through a second-level export are found', () {
    final fx = Fx.baseline({
      'frost_ui.dart': "export 'src/controls/barrel.dart';\n",
      'controls/barrel.dart': "export 'button.dart';\n",
    });
    check(fx.read(apiPath).contains('class\tFrostButton\t'), 'listed:\n${fx.read(apiPath)}');
    fx.edit('controls/button.dart', (s) => '${s}class FrostDeep {}\n');
    final r = fx.run();
    check(r.code == 1 && hasLine(r, 'public-api ', 'FrostDeep'), r.text);
  });

  test('show lists only the shown names', () {
    final fx = Fx.baseline({
      'frost_ui.dart': "export 'src/controls/multi.dart' show ShownA;\n",
      'controls/multi.dart': 'class ShownA {}\nclass NotShown {}\n',
    });
    final api = fx.read(apiPath);
    check(api.contains('ShownA') && !api.contains('NotShown'), api);
    fx.edit('controls/multi.dart', (s) => '${s}class NotShownEither {}\n');
    expectClean(fx);
  });

  test('hide excludes the hidden names', () {
    final fx = Fx.baseline({
      'frost_ui.dart': "export 'src/controls/multi.dart' hide HidA;\n",
      'controls/multi.dart': 'class VisA {}\nclass HidA {}\n',
    });
    final api = fx.read(apiPath);
    check(api.contains('VisA') && !api.contains('HidA'), api);
    fx.edit('controls/multi.dart', (s) => '${s}class HidA2Not {}\n');
    final r = fx.run();
    check(r.code == 1 && hasLine(r, 'public-api ', 'HidA2Not'), 'unhidden new name must fail\n${r.text}');
  });

  test('private names and non-exported files are ignored', () {
    final fx = Fx.baseline({'controls/button.dart': '${buttonSource}class _Hidden {}\n'});
    check(!fx.read(apiPath).contains('_Hidden'), 'private not listed');
    fx.edit('controls/button.dart', (s) => '${s}class _Other {}\nvoid _helper() {}\n');
    fx.write('controls/unexported.dart', 'class Loose {}\nvoid looseFn() {}\n');
    expectClean(fx);
    check(!fx.read(apiPath).contains('Loose'), 'non-exported not listed');
  });

  test('removing an export is stale, --prune fixes it and shortens the list', () {
    final fx = Fx.baseline();
    final before = lineCount(fx.read(apiPath));
    fx.write('frost_ui.dart', "export 'src/foundation/base.dart';\n");
    final r = fx.run();
    check(r.code == 1, 'exit ${r.code}\n${r.text}');
    check(hasStale(r, 'public-api', 'FrostButton'), r.text);
    final p = fx.run(['--prune']);
    check(p.code == 0, 'prune exit ${p.code}\n${p.text}');
    check(lineCount(fx.read(apiPath)) < before, 'list shorter');
    expectClean(fx);
  });

  test('removing a parameter is stale, --prune shrinks the ctor detail', () {
    final fx = Fx.baseline();
    final before = lineCount(fx.read(apiPath));
    fx.write(
      'controls/button.dart',
      'class FrostButton {\n  const FrostButton({required this.label});\n  final String label;\n}\n',
    );
    final r = fx.run();
    check(r.code == 1, 'exit ${r.code}\n${r.text}');
    check(hasStale(r, 'public-api', 'FrostButton.new'), r.text);
    final p = fx.run(['--prune']);
    check(p.code == 0, 'prune exit ${p.code}\n${p.text}');
    check(fx.read(apiPath).contains('ctor\tFrostButton.new\tcontrols/button.dart\tlabel\t'), fx.read(apiPath));
    check(lineCount(fx.read(apiPath)) == before, 'ctor row kept, not removed');
  });

  test('empty source fails with rule public-api', () {
    final fx = Fx.baseline();
    fx.edit(apiPath, (s) => s.replaceFirst('class\tFrostBase\tfoundation/base.dart\t-\t$marker', 'class\tFrostBase\tfoundation/base.dart\t-\t'));
    final r = fx.run();
    check(r.code == 1, 'exit ${r.code}\n${r.text}');
    check(r.lines.any((l) => l.startsWith('public-api ')), r.text);
  });
}

