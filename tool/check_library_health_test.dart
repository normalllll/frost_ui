void listingGroup() {
  bool hasRow(Fx fx, String prefix) => fx.read(apiPath).split('\n').any((l) => l.startsWith(prefix));

  test('a field initialized only by a private constructor is a member', () {
    final fx = withExports({'controls/p.dart': 'class P {\n  const P._(this.secret);\n  final int secret;\n}\n'}, ["export 'src/controls/p.dart';"]);
    check(hasRow(fx, 'member\tP.secret\tcontrols/p.dart\t'), apiRows(fx));
  });

  test('a field set by a public ctor is not a member; one set only privately is', () {
    final fx = withExports({
      'controls/q.dart':
          'class Q {\n  const Q({required this.ok});\n  const Q._(this.hidden, this.ok);\n'
          '  final int ok;\n  final int hidden;\n}\n',
    }, ["export 'src/controls/q.dart';"]);
    check(hasRow(fx, 'member\tQ.hidden\tcontrols/q.dart\t'), apiRows(fx));
    check(!hasRow(fx, 'member\tQ.ok\t'), apiRows(fx));
  });

  test('a field initialized only by an enum constructor is a member', () {
    final fx = withExports({'controls/e.dart': 'enum E {\n  a(1);\n  const E(this.value);\n  final int value;\n}\n'}, ["export 'src/controls/e.dart';"]);
    check(hasRow(fx, 'member\tE.value\tcontrols/e.dart\t'), apiRows(fx));
  });

  test('both branches of a conditional export are listed', () {
    final fx = withExports(
      {
        'controls/thing_stub.dart': 'class Thing {}\n',
        'controls/thing_io.dart': 'class Thing {\n  void ioOnly() {}\n}\n',
      },
      ["export 'src/controls/thing_stub.dart' if (dart.library.io) 'src/controls/thing_io.dart';"],
    );
    check(hasRow(fx, 'class\tThing\tcontrols/thing_stub.dart\t'), apiRows(fx));
    check(hasRow(fx, 'class\tThing\tcontrols/thing_io.dart\t'), apiRows(fx));
    check(hasRow(fx, 'member\tThing.ioOnly\tcontrols/thing_io.dart\t'), apiRows(fx));
  });
}

void rulesGroup() {
  test('destructuring a widget class is not branching', () {
    final fx = Fx.baseline();
