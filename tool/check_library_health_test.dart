/// Inserts a row into a list, keeping comments first and the rows sorted.
void addRow(Fx fx, String path, String row) => fx.edit(path, (s) {
  final lines = s.split('\n').where((l) => l.trim().isNotEmpty).toList();
  final rows = [...lines.where((l) => !l.startsWith('#')), row]..sort();
  return '${[...lines.where((l) => l.startsWith('#')), ...rows].join('\n')}\n';
});

RegExp growthLine(String rest) => RegExp('^growth ${RegExp.escape(rest)}: ');
bool hasGrowth(Res r, String rest) => r.lines.any(growthLine(rest).hasMatch);
int growthLines(Res r) => r.lines.where((l) => l.startsWith('growth ')).length;

