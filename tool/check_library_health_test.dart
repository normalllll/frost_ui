void check(bool ok, String message) {
  if (!ok) throw StateError(message);
}

void test(String name, FutureOr<void> Function() body) =>
    cases.add((name, body));

class Res {
  Res(this.code, String out, this.err)
    : lines = const LineSplitter()
          .convert(out)
          .where((l) => l.trim().isNotEmpty)
          .toList();
  final int code;
  final List<String> lines;
  final String err;
  String get text => '${lines.join('\n')}\n$err';
  String get last => lines.isEmpty ? '' : lines.last;
}

String _path(String k) {
  if (k == 'frost_ui.dart') return '$lib/frost_ui.dart';
  if (k.startsWith('packages/') || k.startsWith('tool/')) return k;
  return '$src/$k';
}

class Fx {
  Fx() : root = Directory.systemTemp.createTempSync('frost-health-') {
    temps.add(root);
  }
  final Directory root;

  File f(String p) => File('${root.path}/${_path(p)}');
  void write(String p, String text) {
    f(p)
      ..parent.createSync(recursive: true)
      ..writeAsStringSync(text);
  }

  String read(String p) => f(p).readAsStringSync();
  bool has(String p) => f(p).existsSync();
  void delete(String p) => f(p).deleteSync();
  void edit(String p, String Function(String) fn) => write(p, fn(read(p)));

  Res run([List<String> args = const []]) {
    final r = Process.runSync('dart', [
      '${repo.path}/tool/check_library_health.dart',
      '--root',
      root.path,
      ...args,
    ]);
    final res = Res(r.exitCode, '${r.stdout}', '${r.stderr}');
    collected.addAll(res.lines);
    return res;
  }

  /// A clean fixture: files written, lists generated by --init, exit 0 proven.
  static Fx baseline([Map<String, String?> extra = const {}]) {
    final fx = Fx();
    final files = {...defaults(), ...extra};
    files.forEach((p, t) {
      if (t != null) fx.write(p, t);
    });
    final i = fx.run(['--init']);
    check(i.code == 0, 'setup: --init should exit 0, got ${i.code}: ${i.text}');
    final c = fx.run();
    check(c.code == 0, 'setup: clean baseline should exit 0, got ${c.code}: ${c.text}');
    return fx;
  }
}

